def embed_and_store_pinecone(chunks, index):
    """Embed chunks and store in Pinecone"""
    if not chunks or not index:
        print("No chunks or index available")
        return

    batch_size = 100

    for i in tqdm(range(0, len(chunks), batch_size), desc="Embedding and storing"):
        batch = chunks[i:i + batch_size]
        vectors_to_upsert = []

        for j, chunk in enumerate(batch):
            try:
                # Generate embedding
                vector = embedding_model.encode(chunk['text']).tolist()

                # Prepare metadata (Pinecone has metadata size limits)
                metadata = {
                    'text': chunk['text'][:1000],  # Limit text size in metadata
                    'file_name': chunk['metadata']['file_name'],
                    'page': chunk['metadata']['page'],
                    'chunk_id': chunk['metadata']['chunk_id']
                }

                vectors_to_upsert.append({
                    'id': f"chunk-{i+j}",
                    'values': vector,
                    'metadata': metadata
                })

            except Exception as e:
                print(f"Error processing chunk {i+j}: {e}")
                continue

        # Upsert batch
        if vectors_to_upsert:
            try:
                index.upsert(vectors_to_upsert)
            except Exception as e:
                print(f"Error upserting batch {i//batch_size}: {e}")

    # Check index stats
    stats = index.describe_index_stats()
    print(f"Index stats: {stats}")

