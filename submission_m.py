def generate_final_answer(parsed_query, matches, threshold=0.80):
    """Generate final answer based on retrieved chunks"""
    if not matches:
        return {
            'answer': 'No information found',
            'rationale': 'No relevant documents found for your query.',
            'confidence': 0.0
        }

    # Filter matches by similarity score
    relevant_matches = [match for match in matches if match['score'] > threshold]

    if not relevant_matches:
        return {
            'answer': 'Insufficient information',
            'rationale': f'Found {len(matches)} potentially relevant documents, but none meet the confidence threshold.',
            'confidence': max([match['score'] for match in matches])
        }

    # Check for entity mentions in top matches
    entity = parsed_query['entity'].lower()
    entity_found = False
    best_match = None

    for match in relevant_matches:
        text = match['metadata']['text'].lower()
        if entity in text:
            entity_found = True
            best_match = match
            break

    if entity_found and best_match:
        # Look for coverage indicators
        text = best_match['metadata']['text'].lower()
        coverage_indicators = ['covered', 'coverage', 'benefit', 'included', 'eligible']
        exclusion_indicators = ['not covered', 'excluded', 'not eligible', 'not included']

        has_coverage = any(indicator in text for indicator in coverage_indicators)
        has_exclusion = any(indicator in text for indicator in exclusion_indicators)

        if has_exclusion:
            answer = 'No'
            rationale = f"The {entity} appears to be excluded based on information found in {best_match['metadata']['file_name']} on page {best_match['metadata']['page']}."
        elif has_coverage:
            answer = 'Yes'
            rationale = f"The {entity} appears to be covered based on information found in {best_match['metadata']['file_name']} on page {best_match['metadata']['page']}."
        else:
            answer = 'Unclear'
            rationale = f"Information about {entity} was found in {best_match['metadata']['file_name']} on page {best_match['metadata']['page']}, but coverage details are unclear."

        return {
            'answer': answer,
            'rationale': rationale,
            'confidence': best_match['score'],
            'source': {
                'file': best_match['metadata']['file_name'],
                'page': best_match['metadata']['page'],
                'text_excerpt': best_match['metadata']['text'][:300]
            }
        }

    else:
        return {
            'answer': 'No specific information found',
            'rationale': f'No specific information about "{entity}" was found in the documents.',
            'confidence': relevant_matches[0]['score'] if relevant_matches else 0.0
        }

