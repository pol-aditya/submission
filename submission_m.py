def clean_text(text):
    text = re.sub(r'\s+', ' ', text)
    return text.strip()

def load_and_chunk_pdf(pdf_path, max_chunk_size=500):
    chunks = []
    try:
        with open(pdf_path, 'rb') as file:
            reader = PyPDF2.PdfReader(file)
            for page_num, page in enumerate(reader.pages):
                try:
                    text = page.extract_text()
                    if not text or len(text.strip()) < 10:
                        continue

                    text = clean_text(text)

                    if len(text) <= max_chunk_size:
                        chunks.append({
                            'text': text,
                            'metadata': {
                                'file_name': os.path.basename(pdf_path),
                                'page': page_num + 1,
                                'chunk_id': f"{os.path.basename(pdf_path)}_page_{page_num + 1}"
                            }
                        })
                    else:
                        words = text.split()
                        current_chunk = []
                        current_length = 0

                        for word in words:
                            if current_length + len(word) > max_chunk_size and current_chunk:
                                chunk_text = ' '.join(current_chunk)
                                chunks.append({
                                    'text': chunk_text,
                                    'metadata': {
                                        'file_name': os.path.basename(pdf_path),
                                        'page': page_num + 1,
                                        'chunk_id': f"{os.path.basename(pdf_path)}_page_{page_num + 1}_chunk_{len(chunks)}"
                                    }
                                })
                                current_chunk = [word]
                                current_length = len(word)
                            else:
                                current_chunk.append(word)
                                current_length += len(word) + 1

                        if current_chunk:
                            chunk_text = ' '.join(current_chunk)
                            chunks.append({
                                'text': chunk_text,
                                'metadata': {
                                    'file_name': os.path.basename(pdf_path),
                                    'page': page_num + 1,
                                    'chunk_id': f"{os.path.basename(pdf_path)}_page_{page_num + 1}_chunk_{len(chunks)}"
                                }
                            })
                except Exception as e:
                    print(f"Error processing page {page_num + 1} of {pdf_path}: {e}")
    except Exception as e:
        print(f"Error reading PDF {pdf_path}: {e}")
        return []

    return chunks

