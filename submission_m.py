import numpy as np

def answer_question_from_chunks(question, chunks, top_k=3):
    """Get top K relevant chunks using cosine similarity"""
    query_embedding = embedding_model.encode(question)
    chunk_similarities = []

    for chunk in chunks:
        chunk_embedding = embedding_model.encode(chunk['text'])
        similarity = float(np.dot(query_embedding, chunk_embedding) /
                           (np.linalg.norm(query_embedding) * np.linalg.norm(chunk_embedding)))

        chunk_similarities.append({
            'chunk': chunk,
            'similarity': similarity
        })

    # Sort by similarity and return top K
    chunk_similarities.sort(key=lambda x: x['similarity'], reverse=True)
    return chunk_similarities[:top_k]

